/**
 * Atomically seeds the default ZX STORE products and packages into Firestore
 * using two ordered batches (products first so package foreign-key checks pass).
 */
export async function seedDefaultCatalogToFirestore(): Promise<void> {
  try {
    const productBatch = writeBatch(db);
    for (const product of DEFAULT_PRODUCTS) {
      const ref = doc(db, 'products', product.id);
      productBatch.set(ref, {
        ...product,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
    }
    await productBatch.commit();

    const pkgBatch = writeBatch(db);
    for (const pkg of DEFAULT_PACKAGES) {
      const ref = doc(db, 'packages', pkg.id);
      pkgBatch.set(ref, {
        ...pkg,
        createdAt: serverTimestamp(),
        updatedAt: serverTimestamp(),
      });
    }
    await pkgBatch.commit();
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, 'products/packages');
  }
}
